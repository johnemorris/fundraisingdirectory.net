export function isTopicIndexable(path) {
  const decision = topicPublication[path];
  if (!decision) throw new Error(`Missing explicit topic publication decision: ${path}`);
  return decision.indexing === "index";
}

export function validateTopicPublication(topics, routes) {
  const expected = routes.filter((route) => !["Fundraising-Resources", "Fundraising-Articles"].includes(route.path)).map((route) => route.path);
  const seen = new Set();
  for (const topic of topics) {
    const path = topic.data?.legacyPath ?? topic.legacyPath;
    if (seen.has(path)) throw new Error(`Duplicate guide route: ${path}`);
    seen.add(path);
    if (topicPublication[path]?.publication !== "guide") throw new Error(`Guide lacks an explicit guide publication decision: ${path}`);
  }
  for (const path of expected) {
    const decision = topicPublication[path];
    if (!decision || !["guide", "placeholder"].includes(decision.publication) || !["index", "noindex"].includes(decision.indexing)) throw new Error(`Invalid topic publication decision: ${path}`);
    if (!decision.reason || !decision.reviewedAt || !["release-brief", "pending-owner", "owner-approved"].includes(decision.approval)) throw new Error(`Missing topic review: ${path}`);
    if (decision.publication === "guide" && !seen.has(path)) throw new Error(`Published guide content is missing: ${path}`);
    if (decision.publication === "placeholder" && decision.indexing !== "noindex") throw new Error(`Incomplete placeholder cannot be indexed: ${path}`);
  }
  for (const path of Object.keys(topicPublication)) if (!expected.includes(path)) throw new Error(`Publication decision has no historical route: ${path}`);
}
